static uint8_t digit[] = {
	0x67, 0x16, 0x1a, 0xff, 0x8e, 0x16, 0xaa, 0x49, 0x34, 0x6d, 0x69, 0xb6, 0xa2, 0xdd, 0x1e, 0xef, };

static void md5_buffer(ut_runner *r)
{
	x_md5 md5;
	x_md5_buffer(data, sizeof data, &md5);
	ut_assert_mem_equal(r, digit, sizeof digit, &md5, sizeof md5);
}

static void md5_sectionally(ut_runner *r)
{
	x_md5_ctx ctx;
	x_md5 md5;
	size_t block_size = 6;

	x_md5_init(&ctx);
	for (int i = 0; i < sizeof data; i+= block_size)
		x_md5_update(&ctx, data + i, x_min(block_size, sizeof data - i));
	x_md5_finish(&ctx, &md5);
	ut_assert_mem_equal(r, digit, sizeof digit, &md5, sizeof md5);
}

void md5_test_init(ut_suite *s)
{
	ut_suite_init(s, "md5.h");
	ut_suite_add(s, md5_buffer);
	ut_suite_add(s, md5_sectionally);
}

